// 내가 작성한 프로젝트 API 핸들러
export const myProjectBoards = http.get(
  `${API_BASE_URL}${API_ENDPOINT.LIBRARY_MY_PROJECT}`,
  ({ request }) => {
    const url = new URL(request.url);
    const page = parseInt(url.searchParams.get('page') || '0');
    const size = parseInt(url.searchParams.get('size') || '10');

    const startIndex = page * size;
    const endIndex = startIndex + size;
    const paginatedBoards = mockMyProjectBoardsData.boards.slice(startIndex, endIndex);

    return HttpResponse.json(
      {
        boards: paginatedBoards,
        page,
        size,
        totalElements: mockMyProjectBoardsData.boards.length,
        totalPages: Math.ceil(mockMyProjectBoardsData.boards.length / size),
      },
      {
        status: 200,
      },
    );
  },
);
