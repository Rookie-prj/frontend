// 보관함 API 핸들러
export const savedBoards = http.get(
  `${API_BASE_URL}${API_ENDPOINT.LIBRARY_SAVED}`,
  ({ request }) => {
    const url = new URL(request.url);
    const page = parseInt(url.searchParams.get('page') || '0');
    const size = parseInt(url.searchParams.get('size') || '10');

    const startIndex = page * size;
    const endIndex = startIndex + size;
    const paginatedBoards = mockSavedBoardsData.boards.slice(startIndex, endIndex);

    return HttpResponse.json(
      {
        boards: paginatedBoards,
        page,
        size,
        totalElements: mockSavedBoardsData.boards.length,
        totalPages: Math.ceil(mockSavedBoardsData.boards.length / size),
      },
      {
        status: 200,
      },
    );
  },
);
